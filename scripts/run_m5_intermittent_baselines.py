def model_definitions() -> list[Any]:
    models: list[Any] = []
    for alpha_p in TSB_ALPHA_P_VALUES:
        alias = f"TSB_ad{TSB_ALPHA_D:.2f}_ap{alpha_p:.2f}"
        models.append(TSB(alpha_d=TSB_ALPHA_D, alpha_p=alpha_p, alias=alias))
    models.append(IMAPA(alias="IMAPA"))
    return models


def model_names() -> list[str]:
    return [model.alias for model in model_definitions()]


def first_day_with_mask(mask: np.ndarray) -> np.ndarray:
    present = mask.any(axis=1)
    first = np.argmax(mask, axis=1).astype(np.int32) + 1
    return np.where(present, first, 0).astype(np.int32)


def _load_reference_artifact(path: Path, actual: np.ndarray, n_series: int, origin: int) -> dict[str, np.ndarray]:
    if not path.is_file():
        raise FileNotFoundError(
            f"Missing reference forecast cache: {path}\n"
            "Run the 20-window Timestral/Seasonal-Naive evaluation first, using "
            "--output artifacts/independent_seasons."
        )
    required = {
        "actual", "seasonal_naive_point", "seasonal_naive_quantiles",
        "timestral_quantiles", "quantile_levels", "revenue_weights",
    }
    with np.load(path, allow_pickle=False) as saved:
        missing = required.difference(saved.files)
        if missing:
            raise ValueError(f"Reference cache {path} is missing {sorted(missing)}")
        data = {key: np.asarray(saved[key]).copy() for key in required}
        if "forecast_start_day" in saved.files:
            saved_origin = int(np.asarray(saved["forecast_start_day"]).item())
            if saved_origin != origin:
                raise ValueError(f"{path} contains d_{saved_origin}, expected d_{origin}")
    if data["actual"].shape != actual.shape or not np.array_equal(data["actual"], actual):
        raise ValueError(
            f"Actuals in {path} do not match the prepared sales matrix for "
            f"d_{origin}..d_{origin + HORIZON - 1}. Check subset row ordering."
        )
    if data["seasonal_naive_point"].shape != (n_series, HORIZON):
        raise ValueError(f"Unexpected Seasonal Naive array shape in {path}")
    if data["timestral_quantiles"].shape[:2] != (n_series, HORIZON):
        raise ValueError(f"Unexpected Timestral array shape in {path}")
    weights = data["revenue_weights"].astype(np.float64, copy=False)
    if weights.shape != (n_series,) or not np.isfinite(weights).all() or (weights < 0).any():
        raise ValueError(f"Invalid revenue weights in {path}")
    if not np.isclose(weights.sum(), 1.0, rtol=1e-5, atol=1e-7):
        raise ValueError(f"Revenue weights in {path} do not sum to 1")
    return data


def build_statsforecast_history(
    train: np.ndarray,
    train_price: np.ndarray,
) -> tuple[pd.DataFrame, np.ndarray]:
    """Build long daily history, trimming only pre-launch rows per series.

    First-live is derived strictly from the training price matrix. Once a
    series becomes price-live, the daily sales sequence (including zero sales
    on later days) is kept intact so that TSB's occurrence-probability update
    has a regular daily time axis.
    """
    live_mask = np.isfinite(train_price)
    first_live = first_day_with_mask(live_mask)
    active_ids = np.flatnonzero(first_live > 0)
    if active_ids.size == 0:
        raise ValueError("No series have become price-live before this forecast origin")

    id_parts: list[np.ndarray] = []
    day_parts: list[np.ndarray] = []
    value_parts: list[np.ndarray] = []
    for series_idx in active_ids:
        start_idx = int(first_live[series_idx]) - 1
        values = np.asarray(train[series_idx, start_idx:], dtype=np.float32)
        if values.size == 0:
            continue
        if not np.isfinite(values).all():
            raise ValueError(f"Non-finite sales in training history for series row {series_idx}")
        if (values < 0).any():
            raise ValueError(f"Negative sales in training history for series row {series_idx}")
        day_idx = np.arange(start_idx, train.shape[1], dtype=np.int32)
        id_parts.append(np.full(values.size, series_idx, dtype=np.int32))
        day_parts.append(day_idx)
        value_parts.append(values)

    if not value_parts:
        raise ValueError("No non-empty histories available for StatsForecast")

    # StatsForecast uses a stable string unique_id key; the value is the row
    # index so we can map forecasts back to the prepared subset matrix.
    ids = np.concatenate(id_parts).astype(str)
    day_indices = np.concatenate(day_parts)
    values = np.concatenate(value_parts)
    dates = M5_DAY1 + pd.to_timedelta(day_indices, unit="D")
    history = pd.DataFrame({
        "unique_id": ids,
        "ds": dates,
        "y": values,
    })
    return history, first_live


def forecast_intermittent_models(
    history: pd.DataFrame,
    n_series: int,
    n_jobs: int,
) -> dict[str, np.ndarray]:
    models = model_definitions()
    names = [model.alias for model in models]
    sf = StatsForecast(models=models, freq="D", n_jobs=n_jobs)
    forecast_df = sf.forecast(df=history, h=HORIZON)
    required_columns = {"unique_id", *names}
    missing_columns = required_columns.difference(forecast_df.columns)
    if missing_columns:
        raise ValueError(
            f"StatsForecast output is missing columns {sorted(missing_columns)}; "
            f"actual columns: {list(forecast_df.columns)}"
        )

    predictions = {name: np.zeros((n_series, HORIZON), dtype=np.float32) for name in names}
    for unique_id, group in forecast_df.groupby("unique_id", sort=False):
        series_idx = int(unique_id)
        ordered = group.sort_values("ds")
        if len(ordered) != HORIZON:
            raise ValueError(
                f"StatsForecast returned {len(ordered)} rows for series row {series_idx}; "
                f"expected {HORIZON}"
            )
        for name in names:
            values = ordered[name].to_numpy(dtype=np.float32, copy=True)
            if not np.isfinite(values).all():
                raise ValueError(f"Non-finite {name} forecast for series row {series_idx}")
            # Sales forecasts cannot be negative; record the raw StatsForecast
            # output nowhere else, but avoid negative units in the evaluation.
            predictions[name][series_idx] = np.maximum(values, 0.0)
    return predictions


def _load_or_create_model_cache(
    cache_path: Path,
    train: np.ndarray,
    train_price: np.ndarray,
    actual: np.ndarray,
    n_jobs: int,
    force: bool,
) -> tuple[dict[str, np.ndarray], np.ndarray]:
    names = model_names()
    if cache_path.is_file() and not force:
        with np.load(cache_path, allow_pickle=False) as saved:
            saved_names = [str(value) for value in saved["model_names"].tolist()]
            if saved_names != names:
                raise ValueError(
                    f"Cached model list in {cache_path} differs from current TSB/IMAPA grid. "
                    "Use --force to regenerate this cache."
                )
            saved_actual = np.asarray(saved["actual"]).copy()
            if saved_actual.shape != actual.shape or not np.array_equal(saved_actual, actual):
                raise ValueError(f"Cached actuals in {cache_path} do not match current data")
            preds = {name: np.asarray(saved[name], dtype=np.float32).copy() for name in names}
        print(f"    Reusing {cache_path}")
        # first_live is needed for diagnostics; recompute it without rebuilding
        # the large long-format StatsForecast input table.
        first_live = first_day_with_mask(np.isfinite(train_price))
        return preds, first_live

    history, first_live = build_statsforecast_history(train, train_price)
    print(
        f"    Fitting {len(names)} models across {history['unique_id'].nunique():,} active series "
        f"({len(history):,} daily observations)"
    )
    predictions = forecast_intermittent_models(history, train.shape[0], n_jobs)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        cache_path,
        actual=actual,
        model_names=np.asarray(names, dtype="U40"),
        **predictions,
    )
    print(f"    Saved {cache_path}")
    return predictions, first_live


def _get_first_sale(train: np.ndarray) -> np.ndarray:
    return first_day_with_mask(train > 0)


def _model_metrics(
    store: str,
    origin: int,
    period: str,
    season: str,
    year: int,
    actual: np.ndarray,
    point_forecasts: dict[str, np.ndarray],
    quantile_forecasts: dict[str, np.ndarray],
    levels: np.ndarray,
    weights: np.ndarray,
    scales: np.ndarray,
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    actual_total = float(actual.sum(dtype=np.float64))
    for model_name, point in point_forecasts.items():
        overall = base._metrics(actual, point)
        wrmsse, excluded, excluded_weight = base._wrmsse_style(actual, point, scales, weights)
        pinball = (
            base._weighted_pinball(actual, quantile_forecasts[model_name], levels, weights)
            if model_name in quantile_forecasts else float("nan")
        )
        forecast_total = float(point.sum(dtype=np.float64))
        aggregate_error = forecast_total - actual_total
        rows.append({
            "store": store.upper(),
            "forecast_start_day": origin,
            "forecast_end_day": origin + HORIZON - 1,
            "season": season,
            "season_year": year,
            "evaluation_period": period,
            "train_days": origin - 1,
            "model": model_name,
            "n_series": int(actual.shape[0]),
            **overall,
            "bottom_level_subset_wrmsse_style": wrmsse,
            "weighted_pinball": pinball,
            "excluded_scale_series": excluded,
            "excluded_revenue_weight": excluded_weight,
            "actual_units_total": actual_total,
            "forecast_units_total": forecast_total,
            "aggregate_error_units": aggregate_error,
            "aggregate_error_pct_actual": (
                100.0 * aggregate_error / actual_total if actual_total > 0 else float("nan")
            ),
            "aggregate_forecast_to_actual_pct": (
                100.0 * forecast_total / actual_total if actual_total > 0 else float("nan")
            ),
            "underforecast": bool(aggregate_error < 0),
        })
    return rows


def _demand_class_rows(
    store: str,
    origin: int,
    actual: np.ndarray,
    point_forecasts: dict[str, np.ndarray],
    train: np.ndarray,
    train_price: np.ndarray,
    weights: np.ndarray,
    scales: np.ndarray,
) -> list[dict[str, Any]]:
    # These classes are strictly post-hoc diagnostics. The StatsForecast models
    # have already been fit without receiving any class labels.
    classes, _, _, _ = base._live_adjusted_demand_class(train, train_price)
    rows: list[dict[str, Any]] = []
    for demand_class in ("Smooth", "Erratic", "Intermittent", "Lumpy", "NoSales", "Unclassified"):
        idx = np.flatnonzero(classes == demand_class)
        if idx.size == 0:
            continue
        class_actual = actual[idx]
        actual_total = float(class_actual.sum(dtype=np.float64))
        class_weight = weights[idx]
        for model_name, point in point_forecasts.items():
            class_point = point[idx]
            forecast_total = float(class_point.sum(dtype=np.float64))
            metrics = base._metrics(class_actual, class_point)
            wrmsse, excluded, excluded_weight = base._wrmsse_style(
                class_actual, class_point, scales[idx], class_weight
            )
            rows.append({
                "store": store.upper(),
                "forecast_start_day": origin,
                "demand_class_posthoc": demand_class,
                "model": model_name,
                "n_series": int(idx.size),
                "revenue_weight_share": float(class_weight.sum()),
                **metrics,
                "actual_units_total": actual_total,
                "forecast_units_total": forecast_total,
                "aggregate_error_units": forecast_total - actual_total,
                "aggregate_error_pct_actual": (
                    100.0 * (forecast_total - actual_total) / actual_total
                    if actual_total > 0 else float("nan")
                ),
                "bottom_level_subset_wrmsse_style": wrmsse,
                "excluded_scale_series": excluded,
                "excluded_revenue_weight": excluded_weight,
            })
    return rows


def _write_outputs(output: Path, metrics_rows: list[dict[str, Any]], class_rows: list[dict[str, Any]]) -> None:
    metrics = pl.DataFrame(metrics_rows).sort(["store", "forecast_start_day", "model"])
    metrics.write_csv(output / "phase_a_metrics.csv")

    # Paired improvements are against Seasonal Naive at the same store/origin.
    comparison_rows: list[dict[str, Any]] = []
    for (store, origin), group in metrics.group_by(
        ["store", "forecast_start_day"], maintain_order=True
    ):
        records = {row["model"]: row for row in group.to_dicts()}
        naive = records["SeasonalNaive7_point"]
        for model_name, candidate in records.items():
            if model_name == "SeasonalNaive7_point":
                continue
            comparison_rows.append({
                "store": store,
                "forecast_start_day": origin,
                "forecast_end_day": candidate["forecast_end_day"],
                "season": candidate["season"],
                "season_year": candidate["season_year"],
                "evaluation_period": candidate["evaluation_period"],
                "model": model_name,
                "mae_improvement_vs_naive_pct": 100.0 * (naive["mae"] - candidate["mae"]) / naive["mae"]
                    if naive["mae"] else float("nan"),
                "rmse_improvement_vs_naive_pct": 100.0 * (naive["rmse"] - candidate["rmse"]) / naive["rmse"]
                    if naive["rmse"] else float("nan"),
                "wape_improvement_vs_naive_pct": 100.0 * (naive["wape"] - candidate["wape"]) / naive["wape"]
                    if naive["wape"] else float("nan"),
                "wrmsse_style_improvement_vs_naive_pct": 100.0 * (
                    naive["bottom_level_subset_wrmsse_style"] - candidate["bottom_level_subset_wrmsse_style"]
                ) / naive["bottom_level_subset_wrmsse_style"]
                    if naive["bottom_level_subset_wrmsse_style"] else float("nan"),
                "weighted_pinball_improvement_vs_naive_pct": (
                    100.0 * (naive["weighted_pinball"] - candidate["weighted_pinball"])
                    / naive["weighted_pinball"]
                    if np.isfinite(candidate["weighted_pinball"]) and naive["weighted_pinball"]
                    else float("nan")
                ),
                "aggregate_error_pct_actual": candidate["aggregate_error_pct_actual"],
                "aggregate_forecast_to_actual_pct": candidate["aggregate_forecast_to_actual_pct"],
                "bias": candidate["bias"],
            })
    pl.DataFrame(comparison_rows).sort(["store", "forecast_start_day", "model"]).write_csv(
        output / "phase_a_comparison.csv"
    )

    numeric_fields = [
        "mae", "rmse", "wape", "bias", "smape",
        "bottom_level_subset_wrmsse_style", "weighted_pinball",
        "aggregate_error_pct_actual", "aggregate_forecast_to_actual_pct",
    ]
    summary_exprs = [pl.len().alias("n_windows")]
    for field in numeric_fields:
        summary_exprs.extend([
            pl.col(field).mean().alias(f"{field}_mean"),
            pl.col(field).std().alias(f"{field}_std"),
        ])
    summary_exprs.append(pl.col("underforecast").sum().alias("underforecast_windows"))
    by_period = metrics.group_by(["store", "model", "evaluation_period"]).agg(summary_exprs)
    overall = metrics.group_by(["store", "model"]).agg(summary_exprs).with_columns(
        pl.lit("all_20_windows").alias("evaluation_period")
    )
    summary = pl.concat([overall, by_period], how="diagonal_relaxed")
    summary.sort(["store", "evaluation_period", "model"]).write_csv(
        output / "phase_a_summary.csv"
    )
    by_period.filter(pl.col("evaluation_period") == "development_2012_2014").sort(
        ["store", "model"]
    ).write_csv(output / "phase_a_development_summary.csv")
    by_period.filter(pl.col("evaluation_period") == "holdout_2015").sort(
        ["store", "model"]
    ).write_csv(output / "phase_a_2015_holdout_summary.csv")

    by_season = metrics.group_by(["store", "model", "season"]).agg(summary_exprs)
    by_season.sort(["store", "season", "model"]).write_csv(
        output / "phase_a_season_summary.csv"
    )
    pl.DataFrame(class_rows).sort(
        ["store", "forecast_start_day", "demand_class_posthoc", "model"]
    ).write_csv(output / "phase_a_demand_class_metrics.csv")


def run_smoke_test(n_jobs: int) -> None:
    """Verify installed StatsForecast models and multi-series forecast interface."""
    dates = pd.date_range("2011-01-29", periods=120, freq="D")
    y1 = np.zeros(120, dtype=np.float32)
    y1[[4, 18, 31, 52, 87, 106]] = [3, 4, 2, 7, 3, 5]
    y2 = np.zeros(120, dtype=np.float32)
    y2[::7] = 2
    y3 = np.zeros(120, dtype=np.float32)
    df = pd.concat([
        pd.DataFrame({"unique_id": "0", "ds": dates, "y": y1}),
        pd.DataFrame({"unique_id": "1", "ds": dates, "y": y2}),
        pd.DataFrame({"unique_id": "2", "ds": dates, "y": y3}),
    ], ignore_index=True)
    result = StatsForecast(models=model_definitions(), freq="D", n_jobs=n_jobs).forecast(
        df=df, h=HORIZON
    )
    names = model_names()
    missing = set(names).difference(result.columns)
    if missing:
        raise RuntimeError(f"Smoke test failed; missing outputs: {sorted(missing)}")
    if len(result) != 3 * HORIZON:
        raise RuntimeError(f"Smoke test expected {3 * HORIZON} forecast rows, got {len(result)}")
    for name in names:
        vals = result[name].to_numpy(dtype=np.float64)
        if not np.isfinite(vals).all() or (vals < -1e-8).any():
            raise RuntimeError(f"Smoke test produced invalid values for {name}")
    all_zero = result.loc[result["unique_id"].astype(str) == "2", names].to_numpy(dtype=np.float64)
    if not np.allclose(all_zero, 0.0):
        raise RuntimeError("All-zero series should receive zero TSB/IMAPA forecasts")
    print("StatsForecast smoke test passed.")
    print(f"  StatsForecast version: {getattr(__import__('statsforecast'), '__version__', 'unknown')}")
    print(f"  Models: {', '.join(names)}")
    print(f"  Forecast horizon: {HORIZON} days; sample series: 3")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stores", nargs="+", default=list(DEFAULT_STORES))
    parser.add_argument("--origins", nargs="+", type=int, default=list(DEFAULT_ORIGINS))
    parser.add_argument("--processed", type=Path, default=Path("data/processed"))
    parser.add_argument("--reference", type=Path, default=Path("artifacts/independent_seasons"),
                        help="input root containing the 20-window Timestral/naive forecast caches")
    parser.add_argument("--output", type=Path, default=Path("artifacts/phase_a_intermittent"))
    parser.add_argument("--n-jobs", type=int, default=1,
                        help="StatsForecast parallel jobs; default 1 to limit memory use")
    parser.add_argument("--force", action="store_true",
                        help="recompute intermittent-model caches even when they already exist")
    parser.add_argument("--smoke-test", action="store_true",
                        help="run a small synthetic test of the installed StatsForecast API, then exit")
    args = parser.parse_args()

    if args.n_jobs < 1:
        parser.error("--n-jobs must be at least 1")
    if len(set(args.origins)) != len(args.origins):
        parser.error("--origins contains duplicate values")
    if not args.stores:
        parser.error("Specify at least one store")
    if args.smoke_test:
        run_smoke_test(args.n_jobs)
        return

    args.output.mkdir(parents=True, exist_ok=True)
    all_metrics: list[dict[str, Any]] = []
    all_class_rows: list[dict[str, Any]] = []
    (args.output / "phase_a_config.json").write_text(json.dumps({
        "stores": [store.upper() for store in args.stores],
        "forecast_start_days": args.origins,
        "horizon": HORIZON,
        "reference_forecast_root": str(args.reference),
        "output_root": str(args.output),
        "tsb_alpha_d_fixed": TSB_ALPHA_D,
        "tsb_alpha_p_grid": list(TSB_ALPHA_P_VALUES),
        "imapa": "StatsForecast IMAPA default implementation",
        "history_policy": (
            "Trim leading pre-launch days using first finite training price; retain the "
            "daily sales observations including zero sales from first-live day onward."
        ),
        "demand_class_usage": "post-hoc diagnostics only; never used as model input",
        "model_selection_period": "2012-2014 development windows",
        "final_temporal_holdout": "2015 seasonal windows",
        "point_only_models": [*model_names()],
    }, indent=2))

    for raw_store in args.stores:
        store = raw_store.lower()
        subset_dir = args.processed / "subsets" / store
        required = [subset_dir / "sales.npy", subset_dir / "price.npy", subset_dir / "series.parquet"]
        missing = [path for path in required if not path.is_file()]
        if missing:
            raise FileNotFoundError(
                f"Store {store.upper()} is not prepared. Missing files:\n" +
                "\n".join(str(path) for path in missing)
            )

        sales = np.load(subset_dir / "sales.npy", mmap_mode="r")
        prices = np.load(subset_dir / "price.npy", mmap_mode="r")
        series = pl.read_parquet(subset_dir / "series.parquet")
        if sales.shape != prices.shape or sales.shape[0] != series.height:
            raise ValueError(
                f"{store.upper()} dimensions differ: sales={sales.shape}, "
                f"prices={prices.shape}, metadata rows={series.height}"
            )
        print(f"\n{'=' * 76}\nStore {store.upper()} | {sales.shape[0]:,} series")

        for origin in args.origins:
            end_day = origin + HORIZON - 1
            if origin <= 1 or end_day > sales.shape[1]:
                raise ValueError(f"Invalid requested window d_{origin}..d_{end_day}")
            train_days = origin - 1
            train = np.asarray(sales[:, :train_days], dtype=np.float32)
            actual = np.asarray(sales[:, train_days:end_day], dtype=np.float32)
            train_price = np.asarray(prices[:, :train_days], dtype=np.float32)
            if actual.shape[1] != HORIZON:
                raise ValueError(f"Incorrect holdout length for {store.upper()} d_{origin}")

            reference_dir = args.reference / store / f"origin_d{origin:04d}_d{end_day:04d}"
            reference_path = reference_dir / "forecasts_and_actuals.npz"
            reference = _load_reference_artifact(reference_path, actual, sales.shape[0], origin)
            levels = reference["quantile_levels"].astype(np.float64, copy=False)
            ts_q = reference["timestral_quantiles"].astype(np.float32, copy=False)
            median_idx = int(np.argmin(np.abs(levels - 0.5)))
            if abs(float(levels[median_idx]) - 0.5) > 1e-5:
                raise ValueError(f"No 0.5 Timestral quantile in {reference_path}")

            cache_path = (
                args.output / store / f"origin_d{origin:04d}_d{end_day:04d}" /
                "intermittent_forecasts.npz"
            )
            predictions, first_live = _load_or_create_model_cache(
                cache_path, train, train_price, actual, args.n_jobs, args.force
            )

            first_sale = _get_first_sale(train)
            scales = base._wrmsse_scales(train, first_sale)
            weights = reference["revenue_weights"].astype(np.float64, copy=False)
            points: dict[str, np.ndarray] = {
                "SeasonalNaive7_point": reference["seasonal_naive_point"].astype(np.float32, copy=False),
                "Timestral_median": ts_q[:, :, median_idx],
            }
            points.update(predictions)
            quantiles = {
                "SeasonalNaive7_point": reference["seasonal_naive_quantiles"].astype(np.float32, copy=False),
                "Timestral_median": ts_q,
            }
            season, year = WINDOW_META.get(origin, ("Custom", 0))
            period = "development_2012_2014" if 2012 <= year <= 2014 else (
                "holdout_2015" if year == 2015 else "custom"
            )
            metric_rows = _model_metrics(
                store, origin, period, season, year, actual, points, quantiles,
                levels, weights, scales,
            )
            class_rows = _demand_class_rows(
                store, origin, actual, points, train, train_price, weights, scales
            )
            all_metrics.extend(metric_rows)
            all_class_rows.extend(class_rows)
            print(
                f"  d_{origin}..d_{end_day} ({season} {year}): evaluated "
                f"{len(points)} point-forecast models"
            )
            del train, actual, train_price, reference, predictions, points, quantiles
            del metric_rows, class_rows, scales, weights, ts_q
            gc.collect()

        del sales, prices, series
        gc.collect()

    if not all_metrics:
        raise RuntimeError("No metrics were produced")
    _write_outputs(args.output, all_metrics, all_class_rows)
    print("\nPhase A intermittent-demand evaluation complete.")
    for filename in (
        "phase_a_metrics.csv", "phase_a_comparison.csv", "phase_a_summary.csv",
        "phase_a_development_summary.csv", "phase_a_2015_holdout_summary.csv",
        "phase_a_season_summary.csv", "phase_a_demand_class_metrics.csv",
    ):
        print(f"  {args.output / filename}")


if __name__ == "__main__":
    main()
