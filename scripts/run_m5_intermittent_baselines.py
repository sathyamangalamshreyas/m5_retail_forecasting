#!/usr/bin/env python3
"""Phase A: TSB and IMAPA baselines on the M5 independent seasonal windows.

The script reuses the saved Timestral and Seasonal Naive forecasts generated by
scripts/run_m5_rolling_origin.py. It does not rerun Timestral.

Inputs for each store/origin:
  data/processed/subsets/<store>/{sales.npy, price.npy, series.parquet}
  artifacts/independent_seasons/<store>/origin_dXXXX_dYYYY/forecasts_and_actuals.npz

Outputs:
  artifacts/phase_a_intermittent/phase_a_metrics.csv
  artifacts/phase_a_intermittent/phase_a_comparison.csv
  artifacts/phase_a_intermittent/phase_a_summary.csv
  artifacts/phase_a_intermittent/phase_a_season_summary.csv
  artifacts/phase_a_intermittent/phase_a_demand_class_metrics.csv

M5 sales history is supplied to TSB/IMAPA from each series' first price-live day
through the forecast origin. Leading pre-launch days are excluded. Daily zeros
from the first live day onward are retained, including days with no observed
sale. The model does not receive future price availability or future sales.

The demand classes in phase_a_demand_class_metrics.csv are post-hoc diagnostics
only. They are never passed to TSB or IMAPA as labels or model inputs.

TSB sensitivity grid:
  alpha_d is fixed at 0.10; alpha_p varies over 0.05, 0.10, 0.20, 0.40.
This isolates the impact of the demand-occurrence probability smoothing rate.
The 2012-2014 windows are the development/tuning period; 2015 is reported
separately as a final temporal holdout.
"""
